"""Offline showcase: original parser + citation binder + an illustrative diagnosis.

No captured code is executed and no model request is made. The diagnosis is a
labelled, human-authored fixture, not an inferred result for arbitrary traces.
"""
from __future__ import annotations

import argparse
from importlib.resources import files
import json
from pathlib import Path

import jsonschema

from .fact_layer.extract import python_facts
from .semantic.evidence import requirement_input
from .semantic.validate import bind_citation


def load_fixture():
    return json.loads(files('data_agent_trace.examples').joinpath('synthetic_trace.json').read_text())


def build_demo():
    fixture = load_fixture()
    by_id = {e['evidence_id']: e for e in fixture['evidence']}
    task = by_id['T0001']
    view = requirement_input({'task': {'instruction': task['text'],
                                      'instruction_ref': task['original_source_ref']}})
    operations, status = python_facts(fixture['code'])
    diagnosis = fixture['illustrative_diagnosis']
    schema = json.loads(files('data_agent_trace.diagnosis').joinpath('schema.json').read_text())
    jsonschema.Draft202012Validator(schema).validate(diagnosis)
    citations = []
    for item in diagnosis['root_cause_chain'] + diagnosis['critical_decision_points']:
        step_ids = item.get('step_ids', [item.get('step_id')])
        if any(sid not in fixture['steps'] for sid in step_ids):
            raise ValueError('Unknown step ID in illustrative diagnosis')
        for eid in item['evidence_ids']:
            if eid not in by_id:
                raise ValueError('Unknown evidence ID in illustrative diagnosis')
    for evidence in fixture['evidence']:
        citations.append(bind_citation({'evidence_id': evidence['evidence_id'],
                                       'quote': evidence['text']}, by_id))
    processor = {
        'synthetic': True,
        'recorded_code_executed_by_demo': False,
        'static_operations': operations,
        'parse_status': status,
        'task_evidence_view': view,
        'illustrative_semantic_annotation': {
            'origin': 'human_authored_illustration',
            'description': 'Monthly revenue aggregation omits the task-required cancellation exclusion.',
            'requirement_evidence_ids': ['T0001'],
            'operation_evidence_ids': ['E0002'],
            'semantic_correctness_certified': False,
        },
    }
    result = {
        'synthetic': True,
        'diagnosis_origin': 'human_authored_illustration',
        'model_calls': 0,
        'diagnosis': diagnosis,
        'literal_citations': citations,
        'validation': {'schema': 'passed', 'evidence_ids': 'passed', 'step_ids': 'passed',
                       'literal_quote_binding': 'passed', 'diagnostic_accuracy_measured': False},
    }
    return processor, result, fixture


def run(output):
    processor, result, fixture = build_demo()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    for name, value in [('processor_output.json', processor), ('diagnosis_output.json', result)]:
        (output / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')
    lines = [
        '# Synthetic trace walkthrough',
        '',
        'All observations and the diagnosis below are illustrative fixture content. '
        'The demo checks interfaces and evidence binding, not model accuracy.',
        '',
        '## Task', '', fixture['evidence'][0]['text'],
        '', '## Trace Processor', '',
        'The original static extractor recognizes the CSV read without running the program. '
        'The requirement view retains the original task text and source reference.',
        '', '```python', fixture['code'].rstrip(), '```',
        '', '## Trace Diagnosis', '',
        result['diagnosis']['summary'],
        '', '### Critical decision', '',
        result['diagnosis']['critical_decision_points'][0]['reasoning'],
        '', '### Evidence', '',
    ]
    for e in fixture['evidence']:
        lines.extend([f"- `{e['evidence_id']}` ({e['role']}): {e['text'].strip()}", ''])
    lines.extend(['## Checks', '',
                  'Schema, declared IDs, and exact quotations passed. '
                  'The diagnosis was supplied by the fixture; it was not generated by a model.'])
    (output / 'report.md').write_text('\n'.join(lines) + '\n')
    return result['validation']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default='demo_output', help='New output directory')
    args = parser.parse_args()
    print(json.dumps(run(args.output), indent=2))


if __name__ == '__main__':
    main()
